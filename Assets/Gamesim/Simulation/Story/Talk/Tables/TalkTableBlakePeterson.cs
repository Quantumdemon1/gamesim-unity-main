        /// <summary>The first talk (layer 1): said whatever it can give, so it reveals the first fact on their sheet.</summary>
        static TalkRow First(string id, string open, TalkReply a, TalkReply b, TalkReply c) => new TalkRow
        {
            Id = id, Owner = Owner, Kind = TalkKind.Layer, Layer = 1, Reveals = true, FromRules = TalkRules.ComesToTalk,
            When = new TalkGate { First = true }, Open = open, Replies = new[] { a, b, c },
        };

        /// <summary>A layer frame (layers 1 to 3): it leads to the next fact on their sheet within its layer.</summary>
        static TalkRow Frame(string id, int layer, string open, TalkReply a, TalkReply b, TalkReply c) => new TalkRow
        {
            Id = id, Owner = Owner, Kind = TalkKind.Layer, Layer = layer, Reveals = true, FromRules = TalkRules.ComesToTalk,
            When = new TalkGate { Layer = layer }, Open = open, Replies = new[] { a, b, c },
        };

        /// <summary>The weekly "where they stand" (layer 4): the honest, neutral and dishonest forms.</summary>
        static TalkRow Standing(string id, string open, TalkReply a, TalkReply b, TalkReply c, string honest, string neutral, string dishonest) => new TalkRow
        {
            Id = id, Owner = Owner, Kind = TalkKind.Standing, Layer = 4, Priority = 70, FromRules = TalkRules.ComesToTalk,
            When = new TalkGate { Layer = 4 }, Open = open, Replies = new[] { a, b, c },
            Standing = new TalkStandingLines { Honest = honest, Neutral = neutral, Dishonest = dishonest },
        };

        /// <summary>A week-event talk (<see cref="TalkEvents"/>): said once, while its event holds, in its window.</summary>
        static TalkRow Event(string id, string ev, string window, string open, TalkReply a, TalkReply b, TalkReply c) => new TalkRow
        {
            Id = id, Owner = Owner, Kind = TalkKind.Event, Layer = 0, FromRules = TalkRules.ComesToTalk,
            When = new TalkGate { Layer = 1, Event = ev, Window = window }, Open = open, Replies = new[] { a, b, c },
        };

        /// <summary>House life (layer 0): in a window when one is given, from a week when one is given.</summary>
        static TalkRow Rhythm(string id, string window, int week, string open, TalkReply a, TalkReply b, TalkReply c) => new TalkRow
        {
            Id = id, Owner = Owner, Kind = TalkKind.Rhythm, Layer = 0, FromRules = TalkRules.ComesToTalk,
            When = new TalkGate { Layer = 1, Window = window, Week = week }, Open = open, Replies = new[] { a, b, c },
        };

        /// <summary>A "the usual" talk (ruling R9): house life in any window, which may come round again once all is spent.</summary>
        static TalkRow Usual(string id, string open, TalkReply a, TalkReply b, TalkReply c) => new TalkRow
        {
            Id = id, Owner = Owner, Kind = TalkKind.Rhythm, Layer = 0, Usual = true, FromRules = TalkRules.ComesToTalk,
            When = new TalkGate { Layer = 1 }, Open = open, Replies = new[] { a, b, c },
        };

        /// <summary>One reply in a tone: the player's words, and theirs when it lands, when it is even and when it grates.</summary>
        static TalkReply R(string tone, string line, string lands, string even, string grates) =>
            new TalkReply { Tone = tone, Line = line, Lands = lands, Even = even, Grates = grates };
    }
