        // ------------------------------------------------------------------ the row forms (spec 5.3 gates, slice-1 shapes)

        /// <summary>A first talk (layer 1, said before any counted talk with them, whatever it can give).</summary>
        static TalkRow First(string id, string open, TalkReply a, TalkReply b, TalkReply c) => new TalkRow
        {
            Id = id, Owner = Owner, Kind = TalkKind.Layer, Layer = 1, Reveals = true, FromRules = TalkRules.ComesToTalk,
